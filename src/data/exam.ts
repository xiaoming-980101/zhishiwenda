export type QuestionType = 'single' | 'multiple' | 'judge' | 'fillBlank' | 'scenario'

export interface QuestionOption {
  label: string
  text: string
}

export interface FillBlankSlot {
  slotId: number
  placeholder: string
  keywords: string[]
}

export interface ScenarioSubQuestion {
  subId: number
  type: 'single' | 'judge' | 'multiple' | 'fillBlank'
  stem: string
  options?: QuestionOption[]
  fillSlots?: FillBlankSlot[]
  answer: string | string[] | boolean
  explanation: string
  proof: string
  score: number
}

export interface PracticeQuestion {
  id: number
  type: QuestionType
  category: string
  tags?: string[]
  difficulty?: string
  stem: string
  options?: QuestionOption[]
  fillSlots?: FillBlankSlot[]
  scenarioDesc?: string
  subQuestions?: ScenarioSubQuestion[]
  answer: string | string[] | boolean | FillBlankSlot[]
  explanation: string
  proof: string
}

export interface ExamSection {
  type: 'single' | 'multiple' | 'judge' | 'fillBlank' | 'scenario'
  title: string
  questionCount: number
  scorePerQuestion: number
  totalScore: number
}

